/** 转为 /ill/ 接口写入格式（纯文字故事，无图片） */
export function toIllSeedPayload(story, index) {
  return {
    picture: '',
    title: `童年时刻·故事${index + 1}`,
    description: story.content,
    type: '童年时刻',
    username: '',
    user_id: story.user_id || '',
  }
}

/** 有场景图的预置故事（供图元上传脚本） */
export function getChildhoodPictureSeeds() {
  return CHILDHOOD_SEED_STORIES.filter((story) => story.file)
}
